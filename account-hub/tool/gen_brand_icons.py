#!/usr/bin/env python3
"""Generates lib/shared/brand/brand_icons.g.dart: a slug -> (IconData, Color)
lookup for only the Simple Icons slugs referenced by the catalog, so the app can
resolve brand glyphs by string at runtime without reflection.
Run: python3 tool/gen_brand_icons.py  (requires `flutter pub get` first)."""
import glob, json, os, re, sys
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
pkg = sorted(glob.glob(os.path.expanduser("~/.pub-cache/hosted/pub.dev/simple_icons-*")))[-1]
icons = set(re.findall(r"static const IconData (\w+) =", open(f"{pkg}/lib/src/icon_data.g.dart").read()))
colors = set(re.findall(r"static const Color (\w+) =", open(f"{pkg}/lib/src/icon_color.g.dart").read()))
cat = json.load(open(f"{root}/assets/catalog/platforms.json"))
def field(slug):
    return ("n" + slug) if slug[0].isdigit() else slug
used, missing = set(), set()
for p in cat["platforms"]:
    s = p.get("icon")
    if not s: continue
    if field(s) in icons: used.add(s)
    else: missing.add(s)
if missing:
    print("WARNING missing slugs (set to null in catalog):", sorted(missing), file=sys.stderr)
lines = ["// GENERATED by tool/gen_brand_icons.py — do not edit.",
         "// Brand glyphs from Simple Icons (CC0). Only slugs used by the catalog are mapped.",
         "import 'package:flutter/widgets.dart';",
         "import 'package:simple_icons/simple_icons.dart';", "",
         "class BrandGlyph {", "  const BrandGlyph(this.icon, this.color);", "  final IconData icon;", "  final Color color;", "}", "",
         "const Map<String, BrandGlyph> brandGlyphs = <String, BrandGlyph>{"]
for s in sorted(used):
    f = field(s)
    col = f"SimpleIconColors.{f}" if f in colors else "Color(0xFF6E6E73)"
    lines.append(f"  '{s}': BrandGlyph(SimpleIcons.{f}, {col}),")
lines += ["};", ""]
os.makedirs(f"{root}/lib/shared/brand", exist_ok=True)
open(f"{root}/lib/shared/brand/brand_icons.g.dart", "w").write("\n".join(lines))
print(f"mapped {len(used)} glyphs; {len(missing)} missing")
